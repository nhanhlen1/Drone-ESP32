#!/usr/bin/env python3
"""Sinh metadata đầy đủ từ XML MAVLink chính thức đã pin, không sửa firmware."""
from pathlib import Path
import argparse, hashlib, importlib.metadata, json, subprocess
from pymavlink.generator import mavparse

PROJECT=Path(__file__).resolve().parents[2]
PIN='e03dad40efb3a4009ad6d78de5e55997139ac2f3'
EXPECTED_GENERATOR='2.4.49'
def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--xml-root',type=Path,default=Path('/workspace/tooling/ardupilot-target-sitl/modules/mavlink/message_definitions/v1.0'))
    args=ap.parse_args()
    root=args.xml_root.resolve()
    actual=subprocess.check_output(['git','-C',str(root),'rev-parse','HEAD'],text=True).strip()
    if actual!=PIN:raise SystemExit('Sai commit MAVLink; không thay bảng metadata.')
    subprocess.run(['git','-C',str(root),'diff','--exit-code','HEAD','--','.'],check=True,stdout=subprocess.DEVNULL)
    if importlib.metadata.version('pymavlink')!=EXPECTED_GENERATOR:raise SystemExit('Sai phiên bản pymavlink generator.')
    messages={};sources={}
    def visit(name):
        if name in sources:return
        p=root/name
        sources[name]=hashlib.sha256(p.read_bytes()).hexdigest()
        parsed=mavparse.MAVXML(str(p),wire_protocol_version='2.0')
        for included in parsed.include:visit(included)
        for m in parsed.message:
            if m.id in messages:raise ValueError('Duplicate message ID '+str(m.id))
            messages[m.id]=(m.name,m.wire_length,m.crc_extra,m.wire_min_length)
    visit('ardupilotmega.xml')
    lines=['package dev.drone.controller.mavlink','',
      '/** Generated by scripts/protocol/generate_dialect.py. Do not hand-edit.',
      f' * Official mavlink/mavlink commit {PIN}.',
      ' * ardupilotmega.xml plus its complete include closure; wire protocol 2.0.',
      ' * CRC metadata validates framing; it does not authenticate sender identity. */',
      'internal object GeneratedArduPilotDialect {',
      '    val messages:Map<Int,MessageDefinition> = mapOf(']
    for id,(name,length,crc,minimum) in sorted(messages.items()):
        lines.append(f'        {id} to MessageDefinition({length}, {crc}, {minimum}, "{name}"),')
    lines+=['    )','}','']
    (PROJECT/'app/src/main/java/dev/drone/controller/mavlink/GeneratedArduPilotDialect.kt').write_text('\n'.join(lines))
    provenance={'upstream':'https://github.com/mavlink/mavlink','commit':PIN,'root_dialect':'ardupilotmega.xml',
      'wire_version':'2.0','generator':'pymavlink','generator_version':EXPECTED_GENERATOR,'message_count':len(messages),
      'generator_mavparse_sha256':hashlib.sha256(Path(mavparse.__file__).read_bytes()).hexdigest(),
      'xml_sha256':dict(sorted(sources.items()))}
    (PROJECT/'docs/MAVLINK_DIALECT_PROVENANCE.json').write_text(json.dumps(provenance,indent=2)+'\n')
    print(f'Generated {len(messages)} messages from {len(sources)} XML files at {PIN}')
if __name__=='__main__':main()
